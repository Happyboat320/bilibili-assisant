def build_dataset():
    rng = random.Random(20261012)
    grouped = {}
    for category, block in TITLES.items():
        titles = block.strip().splitlines()
        assert len(titles) == 25, (category, len(titles))
        items = []
        for index, title in enumerate(titles):
            positive = category in ("访谈", "硬核", "户外")
            rating = (2 if category == "访谈" and index % 3 else 3) if positive else (1 if category == "数码汽车" or index % 5 == 0 else 0)
            items.append({"id": f"synthetic-{list(TITLES).index(category)}-{index:02d}", "title": title,
                          "category": category, "rating": rating, "liked": positive,
                          "split": "train" if index < 20 else "test"})
        grouped[category] = items
    train = []
    # 每一轮 6 种主题各一个，随机轮内顺序；20–120 的前缀仍接近均衡。
    for index in range(20):
        round_items = [items[index] for items in grouped.values()]
        rng.shuffle(round_items)
        train.extend(round_items)
    test = [item for items in grouped.values() for item in items[20:]]
    rng.shuffle(test)
    data = train + test
    assert len({item["title"] for item in data}) == 150
    return data


